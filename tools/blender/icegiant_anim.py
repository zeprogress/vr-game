def shake(t, t0, t1, amp, hz=13.0):
    if t < t0 or t > t1:
        return 0.0
    k = 1 - (t - t0) / (t1 - t0)
    return amp * k * k * math.sin((t - t0) * hz * 2 * math.pi)


