IDLE_SEC = 3.2


def clip_idle(rig_, u):
    tau = 2 * math.pi
    b = math.sin(tau * u)  # вдох (+) / выдох (−)
    p = Pose()
    p.root.z = -0.035 - 0.01 * (1 - b) / 2
    p.root.x = 0.018 * math.sin(tau * u - 0.6)
    p.rot("Hips", 0, -1.6 * math.sin(tau * u - 0.6), 1.2 * math.sin(tau * u))
    p.torso(4 - 2.2 * b, 1.4 * math.sin(tau * u - 0.2), -1.5 * math.sin(tau * u + 0.8))
    # осматривается: медленный поворот головы, на выдохе чуть опускает
    p.head(-3 + 2.5 * (1 - b) / 2, -2 * math.sin(tau * u + 1.3), 11 * math.sin(tau * u + 1.0))
    for s, ph in (("L", 0.0), ("R", 1.7)):
        sw = math.sin(tau * u + ph)
        p.arm(s, (0, -2 - 2.5 * b, -1.5 * b), (-6 + 2.5 * sw, -9 - 1.5 * b, 4), -14 - 4 * b,
              -8 - 7 * math.sin(tau * u + ph + 0.9))
    return p.done()


