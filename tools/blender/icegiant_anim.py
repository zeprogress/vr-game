DEATH_SEC = 3.0


def clip_death(rig_, u):
    t = u * DEATH_SEC
    p = Pose()
    # 0–0.3 шатнулся назад; 0.3–0.9 колени подломились; 0.9–1.25 обмяк на коленях; 1.25–1.85 рухнул вперёд
    fall = K([(0, 0), (1.25, 0), (1.85, 1, "i"), (3.0, 1)], t)
    bounce = K([(0, 0), (1.85, 0), (1.95, 1, "o"), (2.15, 0), (3.0, 0)], t)
    kneel = K([(0, 0), (0.3, 0), (0.9, 1, "i"), (3.0, 1)], t)
    fw = K([(0, 0), (0.3, -16, "o"), (0.9, 10), (1.25, 24), (1.85, 10), (3.0, 6)], t)
    p.torso(fw, K([(0, 0), (0.3, 4), (1.25, -6), (3.0, -4)], t), K([(0, 0), (0.3, 8), (1.25, -4), (3.0, 0)], t))
    p.head(K([(0, 0), (0.3, -24, "o"), (0.9, 18), (1.25, 30), (1.85, -10), (2.4, -4), (3.0, -4)], t),
           K([(0, 0), (1.85, 0), (2.6, 30), (3.0, 30)], t), K([(0, 0), (1.85, 0), (2.6, 16), (3.0, 16)], t))
    # таз: опускается на колени, потом валится вперёд (корпус ложится вдоль −Y)
    p.rot("Hips", 80 * fall, 0, 0)
    p.root.z = -0.035 - 0.4 * kneel - 0.25 * fall + 0.04 * bounce
    p.root.y = 0.08 * kneel - 0.42 * fall
    # руки: вскинулись → повисли → выброшены вперёд-в стороны при падении
    for s in ("L", "R"):
        up = K([(0, (-6, -9, 4)), (0.3, (-40, -44, 10), "o"), (0.9, (-4, -12, 0)), (1.25, (6, -6, 0)),
                (1.85, (-150, -40, 20), "i"), (2.15, (-160, -46, 24)), (3.0, (-158, -48, 22))], t)
        p.arm(s, (0, -2, 0), up, K([(0, -14), (0.3, -40), (0.9, -8), (1.85, -30), (3.0, -34)], t),
              K([(0, -8), (0.3, 20), (1.25, 0), (1.85, -20), (3.0, -16)], t))
    # ноги: на коленях — голени лежат (стопа носком вниз); при падении — вытянуты назад по земле
    p.feet[0] = Vector((0.0, 0.34 * kneel, 0.07 * kneel))
    p.feet[1] = Vector((0.0, 0.34 * kneel, 0.07 * kneel))
    p.pitch = [D(68 * kneel), D(68 * kneel)]
    pose, root, _ = p.done()
    if fall > 0:
        # Лежит: бёдра и голени — FK (стопы больше не стоят), плавно от позы на коленях.
        for side in ("L", "R"):
            fk = {"UpperLeg." + side: Q(10, 0, 0), "LowerLeg." + side: Q(4, 0, 0), "Foot." + side: Q(86, 0, 0)}
            for b, q in fk.items():
                pose[b] = pose[b].slerp(q, fall)
    return pose, root, None


