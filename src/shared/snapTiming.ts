/**
 * Время снимков игрока на клиенте (зритель и игрок). Состояние сервера наблюдают на кадрах рендера,
 * и если кадр подвис, за паузу накапливаются десятки серверных шагов, а в буфер попадает один снимок.
 * Тогда его метка не должна ложиться на шаг сетки: пройденное за паузу проиграется рывком.
 */

/** Скачок, с которого снимок считаем телепортом (м). Меньше — обычное перемещение, даже быстрое. */
export const SNAP_TELEPORT_M = 3;
/** Быстрее этого, м/с, скачок — не бег, а телепорт (рывок ассасина ~6 м за тик — телепорт). */
export const SNAP_SPEED_MAX = 14;

/**
 * Телепорт: новый снимок — не продолжение движения. Возрождение — всегда (смена «мёртв → жив»).
 * Скачок быстрее SNAP_SPEED_MAX за время между наблюдениями — тоже телепорт. Пройденное за
 * подвисание кадра (медленнее порога) — не телепорт: это бег, который растягиваем по времени.
 */
export function isSnapTeleport(jumpM: number, realGapMs: number, respawned: boolean): boolean {
  if (respawned) return true;
  return jumpM > SNAP_TELEPORT_M && jumpM > (realGapMs / 1000) * SNAP_SPEED_MAX;
}

/**
 * Шаг метки от предыдущего снимка, мс. Обычно — шаг сетки серверного темпа. После паузы (кадр, сеть)
 * — реальное время, чтобы пройденное за паузу растянулось на неё, а не сжалось в один шаг.
 */
export function snapshotStep(realGapMs: number, snapDtMs: number): number {
  return realGapMs > snapDtMs * 2.5 ? realGapMs : snapDtMs;
}
