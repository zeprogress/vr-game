/** RGB 0..1 → «#rrggbb» (для HTML/CSS). */
export function rgbHex(c: RGB): string {
  return `#${c.map((v) => Math.round(Math.max(0, Math.min(1, v)) * 255).toString(16).padStart(2, "0")).join("")}`;
}
