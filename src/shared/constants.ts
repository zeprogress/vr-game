/**
 * Виды усиленных мобов из лагерей. `kind` — база ИИ (slime = ближний бой,
 * spitter = дальний). Множители — поверх базового моба этого kind. `scaleMul` —
 * визуальный размер относительно обычного слизня. `tint` — перекрас (null —
 * родная текстура пака).
 */
export interface EliteMobDef {
  model: string;
  name: string;
  /** Уровень моба (табличка/сила). Он же — потолок для расселения ботов в
   *  botHome (ZoneRoom): бот идёт в самый сильный лагерь, чей level не выше
   *  его собственного уровня + 3 (челлендж чуть выше бота, а не ниже). */
  level: number;
  kind: "slime" | "spitter";
  /** Абсолютное HP (не множитель базы): чем выше уровень — тем живучее. */
  hp: number;
  dmgMul: number;
  /** Абсолютный опыт за моба (делится между участниками, не множитель базы). */
  xp: number;
  scaleMul: number;
  tint: readonly [number, number, number] | null;
  /** true — моб парит и не прыгает (пчела): плавно рулит на высоте. */
  flying?: boolean;
  /**
   * Броня против ДАЛЬНЕГО боя: доля 0..1 урона стрел/огнешаров/града, которую
   * съедает панцирь. Ближний бой броню игнорирует — вот и контрплей: лучник
   * такого моба почти не берёт, мечник — берёт. 0/не задано — брони нет.
   */
  rangedArmor?: number;
  /**
   * Физическая броня: доля 0..1 урона МЕЧА и СТРЕЛ (магию не режет). Толстяк
   * с хорошей физ.защитой — контрплей: маг такого моба берёт легко, воин и
   * лучник — упираются. 0/не задано — брони нет.
   */
  physArmor?: number;
  /** Множитель урона МАГИИ (огнешар/АОЕ): >1 — моб уязвим к магии. 1 — обычно. */
  magicVulnMul?: number;
  /** Множитель урона КРИТА (сейчас криты только у лука): >1 — уязвим к критам. */
  critVulnMul?: number;
  /**
   * Новая механика: заряд дальней атаки моба взрывается по площади (обычно
   * мобы бьют только по одной цели). Радиус/доля — в `MAGE_SPELL`.
   */
  spellAoe?: boolean;
  /**
   * Ещё одна новая механика: периодическое заклинание по площади ВОКРУГ
   * СЕБЯ — телеграф (присед/раздутие + кольцо на земле), потом урон, оглушение
   * и отбрасывание всех игроков/ботов в радиусе (см. `MAGE_NOVA`).
   */
  novaCaster?: boolean;
}

