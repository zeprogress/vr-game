/**
 * Круги и метки на земле — одна классификация на все клиенты (веб, VR, Unity-спектатор).
 *
 * Проблема: телеграфов и зон на земле одновременно много (опасности зала, приёмы боссов,
 * метки снарядов, зоны героев), и если рисовать их одинаково — получается каша, по которой
 * нельзя понять, что сейчас произойдёт.
 *
 * Решение: каждая метка принадлежит ОДНОЙ группе, и группа задаёт форму, цвет и поведение.
 * Правило: внутри группы вид одинаковый, между группами — разный. Никаких «украшений»
 * (руны, двойные кольца, искры) в группах, которых на экране может быть много.
 */
export type GroundGroup =
  /** Враг вот-вот ударит по площади: уходи. Обод + заливка-пирог по времени + 4 клина. */
  | "danger"
  /** Постоянная опасность (лава, огонь, яд, шипы): не стой здесь. Штриховка, без пульса. */
  | "persist"
  /** Летит снаряд/глыба/метеор: сюда упадёт. Перекрестие + световой луч, без заливки. */
  | "incoming"
  /** Прицел героя: сюда бей. Тонкий пунктирный круг, дружелюбный цвет, без заливки. */
  | "aim"
  /** Безопасная/лечебная зона: тут хорошо. Мягкое свечение и восходящие искры, без обода. */
  | "safe"
  /** Ульт босса: большое событие. Двойной обод + медленное вращение, максимальный радиус. */
  | "ult";

export interface GroundStyle {
  /** Русское имя для отладки и подсказок. */
  name: string;
  /** Основной цвет (hex, как в shared/look.ts). */
  color: string;
  /** Форма на земле: одна на группу. */
  shape: "pie" | "hatch" | "cross" | "dash" | "glow" | "double";
  /** Насколько ярко рисуем край 0..1. */
  edge: number;
  /** Прозрачность заливки 0..1 (у «опасности» растёт со временем). */
  fill: number;
  /** Есть ли пульсация (у постоянных зон её быть не должно — они и так долго живут). */
  pulse: boolean;
  /** Сколько таких меток держим на экране одновременно (старшие гаснут первыми). */
  maxLive: number;
}

