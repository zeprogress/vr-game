  splitAt?: number;
  splitCount?: number;
  splitScaleMul?: number;
  splitHpFrac?: number;
  splitDmgMul?: number;
  /** Множитель скорости движения осколков (2 — вдвое быстрее родителя). */
  splitSpeedMul?: number;
  splitXp?: number;
  splitChildXp?: number;
